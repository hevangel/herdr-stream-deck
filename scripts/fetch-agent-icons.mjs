/**
 * Downloads official SVG icons for supported herdr agent kinds from
 * @lobehub/icons-static-svg (MIT), saves standalone .svg files into
 * assets/agent-icons/, and generates src/herdr/agent-icons.ts.
 *
 * Usage:
 *   node scripts/fetch-agent-icons.mjs          # download + save SVGs + generate TS
 *   node scripts/fetch-agent-icons.mjs --local  # generate TS from existing assets/agent-icons/*.svg
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const SVG_DIR = resolve(__dirname, "../assets/agent-icons");
const OUT_FILE = resolve(__dirname, "../src/herdr/agent-icons.ts");

// Map herdr agent kind -> candidate @lobehub/icons-static-svg filenames (preferred first)
const ICON_CANDIDATES = {
    claude: ["claude-color", "claude"],
    codex: ["openai", "codex-color"],
    cursor: ["cursor", "cursor-color"],
    agy: ["antigravity"],
    zcode: ["zai", "zai-color", "zhipu-color", "zhipu"],
    copilot: ["githubcopilot", "copilot-color"],
    cline: ["cline"],
    opencode: ["opencode"],
    hermes: ["hermes-color", "hermes", "nousresearch"],
    kiro: ["kiro-color", "kiro"],
    droid: ["factory", "droid"],
    kilo: ["kilocode", "kilo"],
    letta: ["letta"],
};

const BASE = "https://unpkg.com/@lobehub/icons-static-svg@latest/icons";

async function fetchSvg(name) {
    const url = `${BASE}/${name}.svg`;
    const res = await fetch(url);
    if (!res.ok) return null;
    const text = await res.text();
    if (!text.includes("<svg")) return null;
    return { name, url, text };
}

/** Extract viewBox and inner SVG markup, stripping XML/title wrappers. */
function extractInner(svgText) {
    const vbMatch = svgText.match(/viewBox="([^"]+)"/i);
    const viewBox = vbMatch ? vbMatch[1] : "0 0 24 24";
    const openEnd = svgText.indexOf(">");
    const closeStart = svgText.lastIndexOf("</svg>");
    if (openEnd === -1 || closeStart === -1) return null;
    let inner = svgText.slice(openEnd + 1, closeStart).trim();
    inner = inner.replace(/<title>[\s\S]*?<\/title>/gi, "").trim();
    // Replace currentColor with dark ink since icons sit on a white badge tile
    inner = inner.replace(/currentColor/g, "#18181b");
    return { viewBox, inner };
}

function writeTsModule(entries) {
    const lines = [
        "// Auto-generated by scripts/fetch-agent-icons.mjs from assets/agent-icons/*.svg.",
        "// Do not edit by hand; re-run `node scripts/fetch-agent-icons.mjs [--local]` to refresh.",
        "",
        "export interface AgentIconSvg {",
        "    viewBox: string;",
        "    inner: string;",
        "}",
        "",
        `export const AGENT_ICONS: Record<string, AgentIconSvg> = ${JSON.stringify(entries, null, 4)};`,
        "",
    ];
    writeFileSync(OUT_FILE, lines.join("\n"), "utf8");
}

function buildFromLocal() {
    mkdirSync(SVG_DIR, { recursive: true });
    const files = readdirSync(SVG_DIR).filter((f) => f.endsWith(".svg")).sort();
    const entries = {};
    for (const file of files) {
        const kind = basename(file, ".svg").toLowerCase();
        const parsed = extractInner(readFileSync(resolve(SVG_DIR, file), "utf8"));
        if (parsed) entries[kind] = parsed;
    }
    writeTsModule(entries);
    console.log(`Built ${Object.keys(entries).length} icons from assets/agent-icons/`);
}

async function main() {
    if (process.argv.includes("--local")) {
        buildFromLocal();
        return;
    }

    mkdirSync(SVG_DIR, { recursive: true });
    const fetched = [];
    const missed = [];

    for (const [kind, candidates] of Object.entries(ICON_CANDIDATES)) {
        let hit = null;
        for (const cand of candidates) {
            try {
                hit = await fetchSvg(cand);
                if (hit) break;
            } catch {
                // try next candidate
            }
        }
        if (hit) {
            writeFileSync(resolve(SVG_DIR, `${kind}.svg`), hit.text, "utf8");
            fetched.push(`${kind} (${hit.name})`);
        } else {
            missed.push(kind);
        }
    }

    buildFromLocal();
    console.log(`Fetched ${fetched.length} icons: ${fetched.join(", ")}`);
    if (missed.length > 0) console.log(`Fallback to monogram (${missed.length}): ${missed.join(", ")}`);
}

main().catch((err) => {
    console.error(err);
    process.exit(1);
});
